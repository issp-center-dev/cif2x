"""The UPF header reader (standard library only).

The cutoff and valence lookups built on it are tested through their callers
(test_pp_cutoff.py, test_qe_pp_filename.py, test_magnetism.py); these tests
cover the reader itself on the shapes real files take: UPF v2 with a
self-closing PP_HEADER, UPF v1 with a text header and no root element, text
that is not well-formed XML, and files where the header is not near the top.
"""

import pytest

from cif2x.qe.upf import read_upf_header, suggested_cutoffs

_RADIAL = "\n".join("1.0E+00 2.0E+00 3.0E+00 4.0E+00" for _ in range(5000))  # ~160 kB


def _write(tmp_path, text, name="X.UPF", **kwargs):
    path = tmp_path / name
    path.write_text(text, **kwargs)
    return str(path)


# --- UPF v2 -------------------------------------------------------------------

def test_v2_self_closing_header_as_ld1_writes_it(tmp_path):
    # the layout of a pslibrary file: generator input pasted into PP_INFO
    # (bare '&' and '<', so not XML), one long self-closing PP_HEADER
    path = _write(tmp_path, (
        '<UPF version="2.0.1">\n'
        "  <PP_INFO>\n"
        "Generated using \"atomic\" code by A. Dal Corso  v.6.3\n"
        "    Suggested minimum cutoff for wavefunctions:  64. Ry\n"
        "    Suggested minimum cutoff for charge density: 782. Ry\n"
        "    <PP_INPUTFILE>\n &input\n   rlderiv=2.5, eminld=-2.0 < 0\n /\n    </PP_INPUTFILE>\n"
        "  </PP_INFO>\n"
        "  <!--                               -->\n"
        '  <PP_HEADER generated="Generated using &quot;atomic&quot; code" author="ADC"'
        ' element="Fe" pseudo_type="PAW" z_valence="1.600000000000e1"'
        ' wfc_cutoff="6.392614104962e1" rho_cutoff="7.817369433686e2" mesh_size="1191"/>\n'
        '  <PP_MESH>\n' + _RADIAL + "\n  </PP_MESH>\n</UPF>\n"))
    upf = read_upf_header(path)
    assert upf.get("z_valence") == "1.600000000000e1"
    assert upf.get("wfc_cutoff") == "6.392614104962e1"
    assert upf.get("rho_cutoff") == "7.817369433686e2"
    assert upf.get("element") == "Fe"
    assert upf.get("generated") == 'Generated using "atomic" code'   # entity resolved
    assert upf.get("no_such_attribute") is None
    assert upf.text == ""
    assert suggested_cutoffs(upf.info) == (64.0, 782.0)


def test_v2_attributes_over_several_lines_and_quoting(tmp_path):
    path = _write(tmp_path, (
        "<UPF version='2.0.1'>\n<PP_HEADER\n"
        '   comment="a > b / c"\n'
        "   z_valence = '6.0'\n"
        '   WFC_CUTOFF= "30.0"\n'
        '   rho_cutoff ="240.0" />\n</UPF>\n'))
    upf = read_upf_header(path)
    assert upf.attrs == {"comment": "a > b / c", "z_valence": "6.0",
                         "wfc_cutoff": "30.0", "rho_cutoff": "240.0"}


def test_v2_header_with_closing_tag(tmp_path):
    path = _write(tmp_path, '<UPF version="2.0.1">\n<PP_HEADER z_valence="4.0">\n</PP_HEADER>\n</UPF>\n')
    upf = read_upf_header(path)
    assert upf.attrs == {"z_valence": "4.0"}
    assert upf.text.strip() == ""


def test_tag_names_are_case_insensitive(tmp_path):
    path = _write(tmp_path, '<upf>\n<pp_info>\nnote\n</pp_info>\n<pp_header z_valence="7.0"/>\n</upf>\n')
    upf = read_upf_header(path)
    assert upf.get("z_valence") == "7.0"
    assert upf.info.strip() == "note"


def test_similar_tag_name_is_not_the_header(tmp_path):
    path = _write(tmp_path, '<UPF>\n<PP_HEADER_EXTRA z_valence="1.0"/>\n<PP_HEADER z_valence="2.0"/>\n</UPF>\n')
    assert read_upf_header(path).get("z_valence") == "2.0"


# --- UPF v1 -------------------------------------------------------------------

def test_v1_text_header_without_root_element(tmp_path):
    path = _write(tmp_path, (
        "<PP_INFO>\nGenerated by ld1.x\n</PP_INFO>\n"
        "<PP_HEADER>\n   0   Version Number\n  Fe  Element\n"
        "    16.00000000000   Z valence\n"
        "   25.0  200.0  Suggested cutoff for wfc and rho\n"
        "</PP_HEADER>\n<PP_MESH>\n" + _RADIAL + "\n</PP_MESH>\n"))
    upf = read_upf_header(path)
    assert upf.attrs == {}
    lines = [line.split() for line in upf.text.splitlines() if line.strip()]
    assert ["16.00000000000", "Z", "valence"] in lines
    assert ["25.0", "200.0", "Suggested", "cutoff", "for", "wfc", "and", "rho"] in lines
    assert upf.info.strip() == "Generated by ld1.x"


# --- where the elements sit ---------------------------------------------------

def test_header_beyond_the_first_block_is_found(tmp_path):
    # PP_INFO longer than what is read first
    path = _write(tmp_path, ("<UPF>\n<PP_INFO>\n" + _RADIAL + "\n</PP_INFO>\n"
                             '<PP_HEADER z_valence="5.0" wfc_cutoff="50.0"/>\n</UPF>\n'))
    assert read_upf_header(path).get("wfc_cutoff") == "50.0"


def test_info_after_the_header_is_found(tmp_path):
    path = _write(tmp_path, ('<UPF>\n<PP_HEADER z_valence="3.0"/>\n<PP_MESH>\n' + _RADIAL + "\n</PP_MESH>\n"
                             "<PP_INFO>\n    Suggested minimum cutoff for wavefunctions:  33. Ry\n</PP_INFO>\n</UPF>\n"))
    upf = read_upf_header(path)
    assert upf.get("z_valence") == "3.0"
    assert suggested_cutoffs(upf.info) == (33.0, None)


def test_file_without_info(tmp_path):
    path = _write(tmp_path, '<UPF>\n<PP_HEADER z_valence="3.0"/>\n<PP_MESH>\n' + _RADIAL + "\n</PP_MESH>\n</UPF>\n")
    upf = read_upf_header(path)
    assert upf.get("z_valence") == "3.0" and upf.info == ""


# --- not a UPF, unreadable, odd bytes -----------------------------------------

@pytest.mark.parametrize("text", ["", "hello\nworld\n", "<UPF>\n<PP_MESH>\n1.0\n</PP_MESH>\n</UPF>\n"])
def test_no_header_gives_none(tmp_path, text):
    assert read_upf_header(_write(tmp_path, text)) is None


def test_missing_file_raises_oserror(tmp_path):
    with pytest.raises(OSError):
        read_upf_header(str(tmp_path / "none.UPF"))


def test_non_utf8_bytes_do_not_stop_the_read(tmp_path):
    path = _write(tmp_path, ('<UPF>\n<PP_INFO>\nAuthor: K\xfc\xe7\xfckbenli\n</PP_INFO>\n'
                             '<PP_HEADER z_valence="4.0"/>\n</UPF>\n'), encoding="latin-1")
    assert read_upf_header(path).get("z_valence") == "4.0"


# --- the "Suggested" lines of PP_INFO -----------------------------------------

def test_suggested_cutoffs_skip_unset_and_short_lines():
    info = ("    Suggested minimum cutoff for wavefunctions:   0. Ry\n"
            "    Suggested minimum cutoff for charge density:\n"
            "    Suggested minimum cutoff for wavefunctions:  45. Ry\n")
    assert suggested_cutoffs(info) == (45.0, None)
    assert suggested_cutoffs("") == (None, None)
