import pytest

pytest.importorskip("bs4")

from cif2x.pp_cutoff import read_pseudo_cutoff


def _write_upf(path, header_attrs="", pp_info=""):
    body = ""
    if pp_info:
        body += f"<PP_INFO>\n{pp_info}\n</PP_INFO>"
    body += f"<PP_HEADER {header_attrs}/>"
    path.write_text(f"<UPF>{body}</UPF>")


def test_zero_header_cutoff_treated_as_missing(tmp_path):
    # ld1.x-generated UPFs carry rho_cutoff="0.0" when unset: the CSV row must
    # get a blank cell (which cif2x reads as "not specified"), not a literal
    # 0.0 that the generator would then reject as "not found".
    upf = tmp_path / "Fe.UPF"
    _write_upf(upf, header_attrs='wfc_cutoff="40.0" rho_cutoff="0.0"')
    assert read_pseudo_cutoff(str(upf)) == [upf.name, 40.0, ""]


def test_absent_rho_attribute_yields_blank_cell(tmp_path):
    # No rho_cutoff anywhere (header or pp_info): the row is still emitted,
    # with a blank ecutrho cell, instead of dropping the pseudopotential.
    upf = tmp_path / "Fe.UPF"
    _write_upf(upf, header_attrs='wfc_cutoff="40.0"')
    assert read_pseudo_cutoff(str(upf)) == [upf.name, 40.0, ""]


def test_missing_wfc_cutoff_returns_none(tmp_path):
    upf = tmp_path / "Fe.UPF"
    _write_upf(upf, header_attrs='rho_cutoff="320.0"')
    assert read_pseudo_cutoff(str(upf)) is None


def test_pp_info_fills_only_missing_fields(tmp_path):
    # A valid header wfc_cutoff must survive a pp_info block whose
    # "Suggested ... wavefunctions" line carries an unset 0.0.
    upf = tmp_path / "Fe.UPF"
    _write_upf(
        upf,
        header_attrs='wfc_cutoff="40.0"',
        pp_info=(" Suggested minimum cutoff for wavefunctions:    0.0 Ry\n"
                 " Suggested minimum cutoff for charge density: 320.0 Ry"),
    )
    assert read_pseudo_cutoff(str(upf)) == [upf.name, 40.0, 320.0]


def test_csv_key_is_the_bare_file_name(tmp_path):
    # cif2x looks cutoffs up by the file name written to ATOMIC_SPECIES, so a
    # path given on the command line must not end up in the pseudofile column
    sub = tmp_path / "pseudo"
    sub.mkdir()
    upf = sub / "Fe.pbe.UPF"
    _write_upf(upf, header_attrs='wfc_cutoff="40.0" rho_cutoff="320.0"')
    assert read_pseudo_cutoff(str(upf)) == ["Fe.pbe.UPF", 40.0, 320.0]


def test_upf_v1_header_line_is_parsed(tmp_path):
    # UPF v1: no <UPF> root, no attributes; the cutoffs sit in a header text line
    upf = tmp_path / "Fe.v1.UPF"
    upf.write_text(
        "<PP_INFO>\n Generated by ld1.x\n</PP_INFO>\n"
        "<PP_HEADER>\n   0   Version Number\n  Fe  Element\n"
        "   16.00000000000      Z valence\n"
        "   25.00000000000  200.00000000000  Suggested cutoff for wfc and rho\n"
        "</PP_HEADER>\n")
    assert read_pseudo_cutoff(str(upf)) == ["Fe.v1.UPF", 25.0, 200.0]


def test_upf_v1_unset_header_cutoffs_fall_back_to_pp_info(tmp_path):
    upf = tmp_path / "Fe.v1.UPF"
    upf.write_text(
        "<PP_INFO>\n Suggested minimum cutoff for wavefunctions:  47. Ry\n"
        " Suggested minimum cutoff for charge density: 323. Ry\n</PP_INFO>\n"
        "<PP_HEADER>\n    0.00000000000    0.00000000000  Suggested cutoff for wfc and rho\n</PP_HEADER>\n")
    assert read_pseudo_cutoff(str(upf)) == ["Fe.v1.UPF", 47.0, 323.0]


def test_main_writes_csv_with_bare_names(tmp_path, monkeypatch):
    import sys
    from cif2x.pp_cutoff import main
    sub = tmp_path / "pseudo"
    sub.mkdir()
    _write_upf(sub / "Fe.pbe.UPF", header_attrs='wfc_cutoff="40.0" rho_cutoff="320.0"')
    _write_upf(sub / "O.pbe.UPF", header_attrs='wfc_cutoff="50.0"')
    out = tmp_path / "cutoff.csv"
    monkeypatch.setattr(sys, "argv", ["cif2x-pp-cutoff", "-o", str(out), str(sub / "Fe.pbe.UPF"), str(sub / "O.pbe.UPF")])
    main()
    rows = out.read_text().splitlines()
    assert rows[0] == "pseudofile,ecutwfc,ecutrho"
    assert rows[1] == "Fe.pbe.UPF,40.0,320.0"
    assert rows[2] == "O.pbe.UPF,50.0,"
