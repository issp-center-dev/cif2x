import os
import json
from pathlib import Path
import numpy as np
from f90nml.namelist import Namelist

import logging
logger = logging.getLogger(__name__)

class Content:
    def __init__(self):
        self.namelist = None
        self.cards = None
        self.textblock = None

    def render(self):
        import io
        buf = io.StringIO()
        buf.write("! generated by cif2x.py\n")
        self._write_namelist(buf)
        self._write_cards(buf)
        self._write_textblock(buf)
        return buf.getvalue()

    def write_input(self, filename, dirname="."):
        # an OSError (unwritable directory, disk full, ...) propagates so that
        # the CLI reports it and exits with a non-zero status
        logger.debug(f"write_input: dir={dirname}, file={filename}")
        os.makedirs(Path(dirname), exist_ok=True)
        with open(Path(dirname, filename), "w") as fp:
            fp.write(self.render())

    def _write_namelist(self, fp):
        logger.debug("_write_namelist")
        if self.namelist is None:
            return

        # pw.x reads namelists in this fixed order (&system must precede
        # &electrons); unknown sections are appended in insertion order.
        section_order = ["control", "system", "electrons", "ions", "cell", "fcp", "rism"]
        ordered = [s for s in section_order if s in self.namelist]
        ordered += [s for s in self.namelist if s not in section_order]

        # Build f90nml Namelist instances via ordered assignment. f90nml only
        # preserves order for Namelist instances; passing plain dicts makes it
        # alphabetize both sections and keys. Drop keys left as None (at any
        # nesting depth), which would otherwise be emitted as a bad "key = ,"
        # line that QE rejects.
        def _build(tbl, path):
            out = Namelist()
            for k, v in tbl.items():
                key = f"{path}.{k}" if path else k
                if v is None:
                    logger.warning(f"{key} is empty; skipped")
                    continue
                out[k] = _build(v, key) if isinstance(v, dict) else v
            return out

        nml = Namelist()
        for sec in ordered:
            tbl = self.namelist[sec]
            if tbl is None:
                logger.warning(f"namelist section &{sec} is empty; skipped")
                continue
            nml[sec] = _build(tbl, sec)

        nml.write(fp)

    def _write_cards(self, fp):
        logger.debug("_write_cards")
        if self.cards is not None:
            logger.debug(f">>> {self.cards}")
            for key, card in self.cards.items():
                logger.debug(f"--- key={key}, card={card}")
                if "data" in card and card["data"] is not None:
                    fp.write(to_string_block(card))
                    fp.write("\n")

    def _write_textblock(self, fp):
        logger.debug("_write_textblock")
        if self.textblock is not None:
            fp.write(self.textblock)

    def serialize(self):
        return json.dumps({
            'namelist': self.namelist,
            'cards': self.cards,
            'textblock': self.textblock,
        })

    @classmethod
    def deserialize(cls, s):
        v = json.loads(s)
        c = Content()
        c.namelist = v.get("namelist", None)
        c.cards = v.get("cards", None)
        c.textblock = v.get("textblock", None)
        return c

